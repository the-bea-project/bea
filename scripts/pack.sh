#!/usr/bin/env bash
# Build the Bea compiler as a standalone executable with gleepack
# (https://github.com/yoshi-monster/gleepack): one file holding the compiler,
# its dependencies and an Erlang runtime, so `bea` runs where Erlang isn't
# installed. (Bea still needs Gleam, and Gleam needs Erlang to build Erlang
# target projects; `bea transpile`, `format`, `new`, ... don't.)
#
# The compiler is first built from compiler/src by scripts/bootstrap.sh
# (trusted seed A -> B -> C), so the binary contains exactly the verified
# self-hosted compiler; then gleepack packs the repository's Gleam package
# (src/, generated by the bootstrap), with `bea.main` as the entry point.
#
# Usage: scripts/pack.sh [options] [gleepack build options...]
#   --output PATH    Where to write the executable (default: build/bea)
#   --no-bootstrap   Pack the compiler src/ already holds instead of
#                    bootstrapping first
#   Anything else is passed to `gleepack build`, e.g.
#   --target=amd64-linux-otp-29.1.1 (repeatable: one executable per target,
#   the output path suffixed with the target).
#
# gleepack is $BEA_GLEEPACK, or `gleepack` on the PATH (download it from
# https://github.com/yoshi-monster/gleepack/releases). It downloads its
# runtime for the target the first time.
set -euo pipefail

REPO=$(cd "$(dirname "$0")/.." && pwd)
output="$REPO/build/bea"
bootstrap=1
args=()
while [ $# -gt 0 ]; do
  case $1 in
    --output) output=${2:?--output needs a path}; shift ;;
    --output=*) output=${1#--output=} ;;
    --no-bootstrap) bootstrap=0 ;;
    -h | --help) sed -n '2,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
    *) args+=("$1") ;;
  esac
  shift
done
case $output in
  /*) ;;
  *) output="$PWD/$output" ;;
esac

die() { printf '\033[1;31merror:\033[0m %s\n' "$1" >&2; exit 1; }

gleepack=${BEA_GLEEPACK:-}
if [ -z "$gleepack" ]; then
  gleepack=$(command -v gleepack) || die "gleepack not found. Put the gleepack
  executable from https://github.com/yoshi-monster/gleepack/releases on the
  PATH, or set BEA_GLEEPACK to it."
fi
[ -x "$gleepack" ] || die "BEA_GLEEPACK is set to $gleepack, which isn't an executable"

if [ "$bootstrap" = 1 ]; then
  "$REPO/scripts/bootstrap.sh"
elif [ ! -f "$REPO/src/.bea-generated" ]; then
  die "src/ hasn't been generated: run scripts/bootstrap.sh (or drop --no-bootstrap)"
fi

mkdir -p "$(dirname "$output")"
printf '\033[1;35m%-8s\033[0m %s\n' "pack" "the compiler with $gleepack"
(cd "$REPO" && "$gleepack" build --module=bea --output="$output" ${args[@]+"${args[@]}"})

# A smoke test of what was built for this machine (not for other targets).
if [ -x "$output" ]; then
  version=$("$output" --version) || die "$output was built but doesn't run"
  printf '\033[1;35m%-8s\033[0m %s\n' "done" "$output ($version)"
fi
